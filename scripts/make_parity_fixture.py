"""Write the parity fixture core's tests check its TypeScript forward pass against.

A seeded network (not a trained one) and a seeded synthetic RGBA still. For each
pod box the fixture holds what PyTorch computes: the preprocessed input's sum
and first values, the logits and the probabilities. Core's
src/vision/tests/podState.test.ts runs the same boxes through cropInput and
forward and must agree within 1e-4, so CI there needs no Python.

    uv run --locked python scripts/make_parity_fixture.py ../core/src/vision/tests/parity/pod-state-parity.json
"""

from __future__ import annotations

import argparse
import base64
import json
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from seedypod_training.model import PodStateNet, logits_hwc, to_file  # noqa: E402
from seedypod_training.preprocess import ModelInput, Rect, crop_input  # noqa: E402

SEED = 185
WIDTH, HEIGHT = 160, 120
# Fractional boxes, one past the frame's edge, one smaller than the input (cells repeat pixels), one larger.
RECTS = [
    Rect(10.4, 7.6, 70.3, 66.2),
    Rect(120.5, 80.25, 60.0, 50.0),
    Rect(40.0, 30.0, 20.0, 18.0),
    Rect(0.0, 0.0, 160.0, 120.0),
]


def still() -> np.ndarray:
    """An RGBA still with gradients, a green blob and noise, so every averaging cell differs."""
    rng = np.random.default_rng(SEED)
    y, x = np.mgrid[0:HEIGHT, 0:WIDTH]
    r = 40 + x * 1.2 + rng.integers(0, 30, (HEIGHT, WIDTH))
    g = 60 + y * 1.1 + rng.integers(0, 30, (HEIGHT, WIDTH))
    b = 90 + ((x + y) % 23) * 3 + rng.integers(0, 30, (HEIGHT, WIDTH))
    blob = (x - 50) ** 2 + (y - 40) ** 2 < 15**2
    g = np.where(blob, 200, g)
    r = np.where(blob, 50, r)
    rgba = np.stack([r, g, b, np.full_like(r, 255)], axis=-1)
    return np.clip(rgba, 0, 255).astype(np.uint8)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out", type=Path)
    args = ap.parse_args()

    torch.manual_seed(SEED)
    model = PodStateNet()
    inp = ModelInput(mean=(0.45, 0.5, 0.4), std=(0.22, 0.25, 0.2))
    img = still()
    crops = np.stack([crop_input(img, r, inp) for r in RECTS])
    logits = logits_hwc(model, crops)
    probs = torch.softmax(torch.from_numpy(logits), dim=1).numpy()

    doc = {
        "about": "Generated by seedypod/training scripts/make_parity_fixture.py; seeded weights, not a trained model.",
        "model": to_file(model, inp, version=1, revision="parity-fixture", notes="Seeded random weights for the parity test."),
        "image": {"width": WIDTH, "height": HEIGHT, "rgba": base64.b64encode(img.tobytes()).decode("ascii")},
        "cases": [
            {
                "rect": {"x": r.x, "y": r.y, "w": r.w, "h": r.h},
                "inputSum": float(crops[i].astype(np.float64).sum()),
                "inputHead": [float(v) for v in crops[i].reshape(-1)[:12]],
                "logits": [float(v) for v in logits[i]],
                "probabilities": [float(v) for v in probs[i]],
            }
            for i, r in enumerate(RECTS)
        ],
    }
    args.out.write_text(json.dumps(doc, separators=(",", ":")) + "\n")
    print(f"wrote {args.out} ({args.out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
